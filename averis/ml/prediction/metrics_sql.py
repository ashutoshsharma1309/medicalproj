"""Emit the model_metrics seed.

model_metrics is written by the training pipeline, never by the application —
no client role is granted insert on it. So the pipeline emits SQL that a human
pastes into the Supabase SQL editor alongside the schema, in the same way the
migrations are applied.

The insert is idempotent on (model_name, model_version, algorithm), so
re-running a training pass updates the row rather than accumulating a second
copy of the same run.
"""

from __future__ import annotations

import pathlib

SEED_PATH = pathlib.Path(__file__).parents[2] / "supabase" / "seed" / "model_metrics.sql"

HEADER = """-- ===========================================================================
-- AVERIS — model_metrics seed
--
-- Generated by ml/train_all.py. Do not edit by hand; retrain instead.
--
-- Every family that was compared is recorded, not only the one that ships.
-- A patient told they are in a higher-risk range is entitled to see both how
-- well the serving model performs and what it was chosen over.
-- ===========================================================================

"""


def _sql_string(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _sql_number(value: float | None) -> str:
    return "null" if value is None else f"{value:.4f}"


def emit(artifacts: list[dict]) -> pathlib.Path:
    lines = [HEADER]

    for artifact in artifacts:
        lines.append(f"-- {artifact['model']} ({artifact['dataset']['name']})")
        lines.append(
            "insert into public.model_metrics\n"
            "  (model_name, model_version, algorithm, dataset, accuracy, precision, "
            "recall, f1_score, roc_auc, is_serving)\nvalues"
        )

        rows = []
        for algorithm, metrics in artifact["metrics"].items():
            rows.append(
                "  ("
                + ", ".join(
                    [
                        _sql_string(artifact["model"]),
                        _sql_string(artifact["version"]),
                        _sql_string(algorithm),
                        _sql_string(artifact["dataset"]["name"]),
                        _sql_number(metrics.get("accuracy")),
                        _sql_number(metrics.get("precision")),
                        _sql_number(metrics.get("recall")),
                        _sql_number(metrics.get("f1_score")),
                        _sql_number(metrics.get("roc_auc")),
                        "true" if algorithm == artifact["served_algorithm"] else "false",
                    ]
                )
                + ")"
            )

        lines.append(",\n".join(rows))
        lines.append(
            "on conflict (model_name, model_version, algorithm) do update set\n"
            "  accuracy   = excluded.accuracy,\n"
            "  precision  = excluded.precision,\n"
            "  recall     = excluded.recall,\n"
            "  f1_score   = excluded.f1_score,\n"
            "  roc_auc    = excluded.roc_auc,\n"
            "  is_serving = excluded.is_serving;\n"
        )

    SEED_PATH.parent.mkdir(parents=True, exist_ok=True)
    SEED_PATH.write_text("\n".join(lines))
    return SEED_PATH
