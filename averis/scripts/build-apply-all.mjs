#!/usr/bin/env node
/**
 * Regenerates supabase/apply-all.sql from supabase/migrations/.
 *
 * The paste-ready schema existed before this script and was assembled by hand,
 * which is why it silently stopped at IoT Phase 1 while four more migrations
 * landed. A file that claims to be the complete schema and is two phases stale
 * is worse than no file: the person pasting it has no way to tell.
 *
 * The header counts are computed rather than written, for the same reason —
 * "22 tables, 65 RLS policies" was true once.
 *
 *   node scripts/build-apply-all.mjs
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = join(ROOT, "supabase", "migrations");
const OUTPUT = join(ROOT, "supabase", "apply-all.sql");

const RULE = "─".repeat(73);

const files = (await readdir(MIGRATIONS)).filter((f) => f.endsWith(".sql")).sort();
if (files.length === 0) throw new Error("no migrations found");

const bodies = [];
for (const file of files) {
  bodies.push({ file, sql: await readFile(join(MIGRATIONS, file), "utf8") });
}

const all = bodies.map((b) => b.sql).join("\n");
const count = (pattern) => (all.match(pattern) ?? []).length;

const tables = count(/^create table (?:if not exists )?public\./gm);
const policies = count(/^create policy/gm);
const functions = count(/^create or replace function/gm);

const header = `-- ===========================================================================
-- AVERIS — complete schema
--
-- Paste into the Supabase SQL Editor and run once:
--   https://supabase.com/dashboard/project/<project-ref>/sql/new
--
-- ${files.length} migrations: ${tables} tables, ${policies} RLS policies, ${functions} helper
-- functions, the 'medical-documents' storage bucket, pgvector retrieval, the
-- IoT device registry and the care-team access model.
--
-- Afterwards paste the generated seeds, in either order:
--   supabase/seed/model_metrics.sql
--   supabase/seed/knowledge_base.sql
--
-- One caveat this file cannot express: a few migrations add values to enums
-- that earlier migrations created, and Postgres refuses to *use* such a value
-- in the same transaction. The SQL Editor wraps a paste in one transaction,
-- which is exactly the case that breaks — so each ALTER TYPE below is
-- deliberately isolated from anything that references it. Keep it that way.
--
-- Generated by scripts/build-apply-all.mjs — do not edit by hand.
-- ===========================================================================
`;

const sections = bodies.map(
  ({ file, sql }) =>
    `\n-- ${RULE}\n-- ${file}\n-- ${RULE}\n${sql.trimEnd()}\n`,
);

await writeFile(OUTPUT, `${header}${sections.join("")}`, "utf8");

console.log(
  `apply-all.sql ← ${files.length} migrations (${tables} tables, ${policies} policies, ${functions} functions)`,
);
