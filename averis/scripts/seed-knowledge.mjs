/**
 * Emits the knowledge-base seed, embeddings included.
 *
 *     npx tsx scripts/seed-knowledge.mjs
 *
 * `knowledge_documents` and its chunks have no insert grant for any client
 * role — the knowledge base is reference material, not something the
 * application writes. So this emits SQL to paste into the Supabase editor,
 * the same way the Phase 4 model metrics are seeded.
 *
 * Embeddings are computed here rather than in the database because the model
 * lives in Node. Baking the vectors into the SQL means applying the seed needs
 * no API key, no model download and no network — it is just an insert.
 *
 * The file is large (384 floats per chunk) and that is the intended trade: a
 * one-time paste in exchange for a seed that cannot half-apply.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { pipeline } from "@huggingface/transformers";

import { KNOWLEDGE_BASE } from "../lib/rag/knowledge-base.ts";
import { chunkText } from "../lib/rag/chunking.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "supabase", "seed", "knowledge_base.sql");

const quote = (value) => "'" + String(value).replace(/'/g, "''") + "'";
const vector = (values) => `'[${values.join(",")}]'::extensions.vector`;

console.log("Loading all-MiniLM-L6-v2 (first run downloads ~23 MB)...");
const extractor = await pipeline("feature-extraction", "Xenova/all-MiniLM-L6-v2");

const lines = [
  "-- ===========================================================================",
  "-- AVERIS — medical knowledge base seed",
  "--",
  "-- Generated by scripts/seed-knowledge.mjs. Do not edit by hand.",
  "--",
  "-- Apply AFTER supabase/apply-all.sql. Re-running is safe: each document is",
  "-- upserted on its title and its chunks are replaced rather than appended.",
  "--",
  "-- Embeddings are all-MiniLM-L6-v2, 384 dimensions, L2-normalised.",
  "-- ===========================================================================",
  "",
  "begin;",
  "",
];

let totalChunks = 0;

for (const entry of KNOWLEDGE_BASE) {
  // The title is prepended so a chunk carries its subject even when the split
  // lands mid-article — otherwise a chunk of ranges retrieves with no idea
  // which test it belongs to.
  const chunks = chunkText(`${entry.title}\n\n${entry.body}`);

  const vectors = (
    await extractor(
      chunks.map((c) => c.content.slice(0, 1600)),
      { pooling: "mean", normalize: true },
    )
  ).tolist();

  lines.push(
    `-- ${entry.title}`,
    "insert into public.knowledge_documents (title, category, body, citation) values",
    `  (${quote(entry.title)}, ${quote(entry.category)}, ${quote(entry.body)}, ${quote(entry.citation)})`,
    "on conflict (title) do update set",
    "  category = excluded.category,",
    "  body     = excluded.body,",
    "  citation = excluded.citation;",
    "",
    "-- Chunks are replaced, never appended: a shorter re-chunking would",
    "-- otherwise leave the tail of the previous version in the index.",
    "delete from public.knowledge_embeddings",
    ` where knowledge_document_id = (select id from public.knowledge_documents where title = ${quote(entry.title)});`,
    "",
    "insert into public.knowledge_embeddings",
    "  (source_type, knowledge_document_id, chunk_index, content, embedding, metadata)",
    "values",
  );

  const rows = chunks.map((chunk, i) => {
    totalChunks += 1;
    const metadata = JSON.stringify({
      title: entry.title,
      category: entry.category,
      citation: entry.citation,
    });
    return (
      "  ('MEDICAL_KNOWLEDGE', " +
      `(select id from public.knowledge_documents where title = ${quote(entry.title)}), ` +
      `${chunk.index}, ${quote(chunk.content)}, ${vector(vectors[i])}, ${quote(metadata)}::jsonb)`
    );
  });

  lines.push(`${rows.join(",\n")};`, "");
}

lines.push("commit;", "");

const sql = lines.join("\n");
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, sql);

console.log(
  `Wrote ${KNOWLEDGE_BASE.length} documents / ${totalChunks} chunks ` +
    `(${(Buffer.byteLength(sql) / 1024).toFixed(0)} KB) to supabase/seed/knowledge_base.sql`,
);
